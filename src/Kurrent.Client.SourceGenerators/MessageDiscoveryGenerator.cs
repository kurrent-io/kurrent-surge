namespace Kurrent.Client.SourceGenerators;

using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

[Generator]
public class MessageDiscoveryGenerator : IIncrementalGenerator {
    public void Initialize(IncrementalGeneratorInitializationContext context) {
        // 1. Efficiently find all MessageDiscovery attributes on the assembly
        var provider = context.SyntaxProvider.ForAttributeWithMetadataName(
            "MyMessaging.MessageDiscoveryAttribute",
            predicate: (n, _) => n is CompilationUnitSyntax || n is AttributeListSyntax,
            transform: (ctx, _) => ctx.Attributes);

        // 2. Combine attributes with the compilation to perform semantic analysis
        var input = provider.Collect().Combine(context.CompilationProvider);

        context.RegisterSourceOutput(
            input, (spc, source) => {
                var allAttributes = source.Left;
                var compilation   = source.Right;
                var foundTypes    = new HashSet<string>();

                // Flatten all attributes found across all files
                foreach (var attributeList in allAttributes) {
                    foreach (var attr in attributeList) {
                        // Mandatory: First positional constructor argument
                        var prefix = attr.ConstructorArguments.FirstOrDefault().Value?.ToString();

                        // Optional: Named arguments
                        var interfaceSymbol = attr.NamedArguments
                            .FirstOrDefault(a => a.Key == "MustImplement")
                            .Value.Value as INamedTypeSymbol;

                        if (string.IsNullOrEmpty(prefix))
                            continue;

                        // 3. Scan the compilation for matching types
                        var matches = ScanForTypes(compilation.GlobalNamespace, prefix!, interfaceSymbol);

                        foreach (var m in matches)
                            foundTypes.Add(m);
                    }
                }

                // 4. Generate the high-performance switch-based resolver
                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated/>");
                sb.AppendLine("using System;");
                sb.AppendLine("namespace MyMessaging.Generated;");
                sb.AppendLine("public static class MessageResolver");
                sb.AppendLine("{");
                sb.AppendLine("    public static Type? Resolve(string name) => name switch");
                sb.AppendLine("    {");

                foreach (var type in foundTypes.OrderBy(t => t))
                    sb.AppendLine($"        \"{type}\" => typeof({type}),");

                sb.AppendLine("        _ => null");
                sb.AppendLine("    };");
                sb.AppendLine("}");

                spc.AddSource("MessageResolver.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
            });
    }

    static IEnumerable<string> ScanForTypes(INamespaceSymbol ns, string prefix, INamedTypeSymbol? interfaceSymbol) {
        var types = new List<string>();
        var stack = new Stack<INamespaceSymbol>();
        stack.Push(ns);

        while (stack.Count > 0) {
            var currentNs = stack.Pop();

            foreach (var type in currentNs.GetTypeMembers()) {
                if (type.IsAbstract || type.DeclaredAccessibility != Accessibility.Public)
                    continue;

                string fullName = type.ToDisplayString();

                if (fullName.StartsWith(prefix)) {
                    // If MustImplement is provided, check it; otherwise include all in namespace
                    if (interfaceSymbol == null || type.AllInterfaces.Any(i => SymbolEqualityComparer.Default.Equals(i, interfaceSymbol)))
                        types.Add(fullName);
                }
            }

            foreach (var subNs in currentNs.GetNamespaceMembers())
                stack.Push(subNs);
        }

        return types;
    }
}