using System.Diagnostics.CodeAnalysis;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using Kurrent.CodeAnalysis;
using Kurrent.CodeAnalysis.Pipeline;
using TypeKind = Kurrent.CodeAnalysis.TypeKind;

namespace Kurrent.Client.SourceGenerators;

[Generator]
[SuppressMessage("MicrosoftCodeAnalysisReleaseTracking", "RS2008:Enable analyzer release tracking")]
public sealed class KurrentOperationErrorGenerator : IIncrementalGenerator {
    public void Initialize(IncrementalGeneratorInitializationContext context) {
        context
            .Types(t => t
                .WithAttribute("Kurrent.Client.KurrentOperationErrorAttribute")
                .OfKind(TypeKind.Class)
                .Is(TypeTraits.Partial))
            .Select(t => new OperationErrorInfo(
                Name: t.Name,
                FullName: t.FullName,
                Namespace: t.Namespace,
                Containers: t.ContainingTypes))
            .ReportWhenEmpty(NoTargetTypesFound)
            .RegisterSources((spc, info) => {
                try {
                    spc.ReportDiagnostic(Diagnostic.Create(FoundTarget, Location.None, info.FullName));

                    var source   = GenerateImplementation(info);
                    var hintName = GenerateHintName(info);
                    spc.AddSource(hintName, SourceText.From(source, Encoding.UTF8));

                    spc.ReportDiagnostic(Diagnostic.Create(ImplementationGenerated, Location.None, info.FullName));
                }
                catch (Exception ex) {
                    spc.ReportDiagnostic(Diagnostic.Create(Failed, Location.None, ex.ToString()));
                }
            });
    }

    static readonly DiagnosticDescriptor FoundTarget = new(
        id: "KURRENT202",
        title: nameof(KurrentOperationErrorGenerator),
        messageFormat: $"[{nameof(KurrentOperationErrorGenerator)}] found type: {{0}}",
        category: "CodeGeneration",
        defaultSeverity: DiagnosticSeverity.Info,
        isEnabledByDefault: true);

    static readonly DiagnosticDescriptor Failed = new(
        id: "KURRENT500",
        title: nameof(KurrentOperationErrorGenerator),
        messageFormat: $"[{nameof(KurrentOperationErrorGenerator)}] failed: {{0}}",
        category: "Error",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    static readonly DiagnosticDescriptor ImplementationGenerated = new(
        id: "KURRENT200",
        title: nameof(KurrentOperationErrorGenerator),
        messageFormat: $"[{nameof(KurrentOperationErrorGenerator)}] completed code generation for: {{0}}",
        category: "CodeGeneration",
        defaultSeverity: DiagnosticSeverity.Info,
        isEnabledByDefault: true);

    static readonly DiagnosticDescriptor NoTargetTypesFound = new(
        id: "KURRENT404",
        title: nameof(KurrentOperationErrorGenerator),
        messageFormat: $"[{nameof(KurrentOperationErrorGenerator)}] no target types found for code generation",
        category: "CodeGeneration",
        defaultSeverity: DiagnosticSeverity.Info,
        isEnabledByDefault: true);

    static string GenerateImplementation(OperationErrorInfo info) {
        var sourceBuilder = new StringBuilder(
            """
            // <auto-generated />
            // This file was generated by the KurrentOperationExceptionGenerator
            // Changes to this file will be lost when the file is regenerated.

            #nullable enable

            {USING_STATEMENTS}

            {NAMESPACE_DECLARATION}

            """);

        sourceBuilder
            .Replace("{USING_STATEMENTS}", GenerateUsingStatements())
            .Replace("{NAMESPACE_DECLARATION}", GenerateNamespaceDeclaration(info.Namespace));

        const string tab = "    ";

        var declarationIndent = "";

        foreach (var c in info.Containers) {
            declarationIndent += tab;
            sourceBuilder.AppendLine($"{declarationIndent}{RenderContainerHeader(c)} {{");
        }

        var memberIndent = declarationIndent;

        const string codeBlock = """
                [PublicAPI, CompilerGenerated, GeneratedCode("KurrentOperationExceptionGenerator", "1.0.0")]
                public partial class {INSTANCE_NAME} : KurrentException, IKurrentOperationException<{INSTANCE_NAME}> {
                    public static ErrorCode Code { get; } = typeof({INSTANCE_NAME}).GetCustomAttribute<KurrentOperationErrorAttribute>()!.ErrorCode;

                    public {INSTANCE_NAME}(string message) : base(Code, message, innerException: null) { }

                    public {INSTANCE_NAME}(Status status) : base(Code, status) {
                        try {
                            ((IKurrentOperationException<{INSTANCE_NAME}>)this).AfterParseRpcStatus(status, this);
                        }
                        catch (Exception ex) {
                            throw new UnreachableException("EVERYTHING IS BROKEN! The {INSTANCE_NAME}::AfterParseRpcStatus hook threw an exception.", ex);
                        }
                    }

                    public static bool TryParseRpcStatus(Status status, ErrorInfo? errorInfo, [MaybeNullWhen(false)] out {INSTANCE_NAME} ex) =>
                        (ex = Code.MatchesRpcStatusReason(status, errorInfo) ? new(status) : null) is not null;

                    public static {INSTANCE_NAME}? From(Status status, ErrorInfo? errorInfo = null) => TryParseRpcStatus(status, errorInfo, out var ex) ? ex : null;
                }
            """;

        var indentedCode = Regex.Replace(codeBlock, @"(?<=\n)", memberIndent);

        sourceBuilder
            .Append(memberIndent + indentedCode)
            .Replace("{INSTANCE_NAME}", info.Name);

        sourceBuilder.AppendLine();

        for (var i = info.Containers.Length - 1; i >= 0; i--) {
            declarationIndent = declarationIndent.Substring(0, declarationIndent.Length - tab.Length);
            sourceBuilder.AppendLine($"{memberIndent + declarationIndent}}}");
        }

        sourceBuilder
            .Append('}')
            .AppendLine();

        sourceBuilder
            .AppendLine()
            .Replace("{INSTANCE_NAME}", info.Name);

        return sourceBuilder.ToString();
    }

    static string GenerateUsingStatements() {
        var sb = new StringBuilder();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.CodeDom.Compiler;");
        sb.AppendLine("using System.Diagnostics;");
        sb.AppendLine("using System.Diagnostics.CodeAnalysis;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using System.Reflection;");
        sb.AppendLine("using Google.Rpc;");
        sb.AppendLine("using Google.Rpc.Exceptions;");
        sb.AppendLine("using Kurrent;");
        sb.AppendLine("using Kurrent.Client;");
        sb.AppendLine("using Kurrent.Client.Errors;");
        sb.AppendLine("using Kurrent.Client.Exceptions;");
        sb.AppendLine("using Kurrent.GoogleRpc;");
        sb.AppendLine("using Kurrent.Rpc;");
        return sb.ToString().TrimEnd();
    }

    static string GenerateNamespaceDeclaration(string ns) =>
        ns != "" ? $"namespace {ns} {{" : "// Global namespace";

    static string RenderContainerHeader(ContainingTypeRef c) {
        var sb = new StringBuilder();

        if (c.Traits.HasFlag(TypeTraits.Public))
            sb.Append("public ");
        else if (c.Traits.HasFlag(TypeTraits.Internal))
            sb.Append("internal ");
        else if (c.Traits.HasFlag(TypeTraits.Protected))
            sb.Append("protected ");

        if (c.Traits.HasFlag(TypeTraits.Static))
            sb.Append("static ");

        if (c.Traits.HasFlag(TypeTraits.ReadOnly))
            sb.Append("readonly ");
        else if (c.Traits.HasFlag(TypeTraits.Abstract) && !c.Traits.HasFlag(TypeTraits.Sealed))
            sb.Append("abstract ");
        else if (!c.Traits.HasFlag(TypeTraits.Abstract) && c.Traits.HasFlag(TypeTraits.Sealed))
            sb.Append("sealed ");

        sb.Append("partial ");

        sb.Append(
            c.Kind switch {
                TypeKind.RecordStruct => "record struct ",
                TypeKind.Record       => "record ",
                TypeKind.Struct       => "struct ",
                TypeKind.Interface    => "interface ",
                TypeKind.Enum         => "enum ",
                _                     => "class "
            });

        sb.Append(c.Name);
        return sb.ToString();
    }

    static string GenerateHintName(OperationErrorInfo info) {
        var name = Sanitize(info.Name);
        var ns   = Sanitize(info.Namespace);
        return $"{ns}_{name}.g.cs";

        static string Sanitize(string input) =>
            input.Replace(' ', '_').Replace('-', '_').Replace('+', '_').Replace('<', '_').Replace('>', '_');
    }

    sealed record OperationErrorInfo(
        string Name,
        string FullName,
        string Namespace,
        ContainingTypeRef[] Containers
    ) {
        public bool Equals(OperationErrorInfo? other) =>
            other is not null
         && Name == other.Name
         && FullName == other.FullName
         && Namespace == other.Namespace
         && Containers.AsSpan().SequenceEqual(other.Containers.AsSpan());

        public override int GetHashCode() {
            var hash = HashCombine.Start;
            hash = HashCombine.Add(hash, Name);
            hash = HashCombine.Add(hash, FullName);
            hash = HashCombine.Add(hash, Namespace);
            hash = HashCombine.AddRange(hash, Containers);
            return hash;
        }
    }
}