using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Kurrent.Surge.Generators.Validation;

/// <summary>
/// Emits the validation wiring for a <c>[WithValidation]</c> type: the interface implementation,
/// the validator, and a <c>Validate</c> that runs the rules on every call.
/// </summary>
/// <remarks>
/// Deliberately smaller than <c>[SelfValidating]</c>. Nothing is cached, so nothing has to be
/// invalidated: properties keep whatever shape their author gave them, and the verdict always
/// describes the object as it is now.
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class WithValidationGenerator : IIncrementalGenerator {
    const string AttributeMetadataName = "Kurrent.Surge.Validation.WithValidationAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var provider = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                AttributeMetadataName,
                predicate: static (node, _) => node is TypeDeclarationSyntax,
                transform: static (ctx, token) => ValidatedTypeModel.From(ctx, token))
            .Where(static m => m is not null);

        context.RegisterSourceOutput(provider, static (ctx, model) => {
            foreach (var diagnostic in model!.Diagnostics)
                ctx.ReportDiagnostic(diagnostic.ToDiagnostic());

            if (model.Diagnostics.Any(d => d.IsError))
                return;

            ctx.AddSource($"{model.HintName}.g.cs", SourceText.From(Emit(model), Encoding.UTF8));
        });
    }

    static string Emit(ValidatedTypeModel model) {
        var writer = new StringBuilder();

        writer.AppendLine("// <auto-generated/>");
        writer.AppendLine("#nullable enable");
        writer.AppendLine();

        if (model.Namespace.Length > 0) {
            writer.Append("namespace ").Append(model.Namespace).AppendLine(";");
            writer.AppendLine();
        }

        foreach (var containing in model.ContainingTypes)
            writer.Append("partial class ").Append(containing).AppendLine(" {");

        writer
            .Append("partial class ").Append(model.TypeName)
            .AppendLine(" : global::Kurrent.Surge.Validation.ISelfValidating {");

        writer
            .Append("    public sealed class Validator : global::Kurrent.Surge.Validation.Validator<Validator, ")
            .Append(model.TypeName).AppendLine("> {");
        writer.AppendLine("        public Validator() => ConfigureRules(this);");
        writer.AppendLine("    }");
        writer.AppendLine();

        writer.AppendLine("    static partial void ConfigureRules(Validator rules);");
        writer.AppendLine();
        writer.AppendLine("    static readonly Validator __rules = new();");
        writer.AppendLine();

        writer.AppendLine("    /// <summary>Runs the configured rules against the object's current state.</summary>");
        writer.AppendLine("    public global::Kurrent.Surge.Validation.ValidationResult Validate() => __rules.Validate(this);");
        writer.AppendLine();

        writer.AppendLine("    /// <summary>");
        writer.AppendLine("    /// Runs validation and throws when the object is invalid, logging warning-severity");
        writer.AppendLine("    /// problems to <paramref name=\"logger\"/> when one is supplied.");
        writer.AppendLine("    /// </summary>");
        writer.AppendLine("    public void EnsureValid(global::Microsoft.Extensions.Logging.ILogger? logger = null) {");
        writer.AppendLine("        var result = Validate();");
        writer.AppendLine();
        writer.AppendLine("        if (logger is null)");
        writer.AppendLine("            result.EnsureValid();");
        writer.AppendLine("        else");
        writer.AppendLine("            result.EnsureValid(logger);");
        writer.AppendLine("    }");

        writer.AppendLine("}");

        foreach (var _ in model.ContainingTypes)
            writer.AppendLine("}");

        return writer.ToString();
    }
}

sealed record ValidatedTypeModel(
    string Namespace,
    string TypeName,
    ImmutableArray<string> ContainingTypes,
    ImmutableArray<DiagnosticModel> Diagnostics
) {
    public string HintName {
        get {
            var path = string.Join(".", ContainingTypes.Append(TypeName));

            return Namespace.Length == 0 ? path : $"{Namespace}.{path}";
        }
    }

    public bool Equals(ValidatedTypeModel? other) =>
        other is not null
        && Namespace == other.Namespace
        && TypeName == other.TypeName
        && ContainingTypes.SequenceEqual(other.ContainingTypes)
        && Diagnostics.SequenceEqual(other.Diagnostics);

    public override int GetHashCode() {
        var hash = Namespace.GetHashCode() ^ TypeName.GetHashCode();

        foreach (var containing in ContainingTypes)
            hash = (hash * 397) ^ containing.GetHashCode();

        foreach (var diagnostic in Diagnostics)
            hash = (hash * 397) ^ diagnostic.GetHashCode();

        return hash;
    }

    public static ValidatedTypeModel? From(GeneratorAttributeSyntaxContext context, System.Threading.CancellationToken token) {
        if (context.TargetSymbol is not INamedTypeSymbol symbol)
            return null;

        var diagnostics = ImmutableArray.CreateBuilder<DiagnosticModel>();
        var anchor      = (TypeDeclarationSyntax)context.TargetNode;

        if (anchor is not ClassDeclarationSyntax)
            diagnostics.Add(Diag("KVAL005", "Only classes are supported",
                $"'{symbol.Name}' is not a class; [WithValidation] supports classes only.", true, anchor.Identifier));

        var declarations = symbol.DeclaringSyntaxReferences
            .Select(reference => reference.GetSyntax(token))
            .OfType<TypeDeclarationSyntax>()
            .ToArray();

        foreach (var declaration in declarations) {
            if (!declaration.Modifiers.Any(SyntaxKind.PartialKeyword))
                diagnostics.Add(Diag("KVAL001", "Type must be partial",
                    $"'{symbol.Name}' is [WithValidation] and must be declared partial.", true, declaration.Identifier));
        }

        var containing = ImmutableArray.CreateBuilder<string>();

        for (var outer = symbol.ContainingType; outer is not null; outer = outer.ContainingType) {
            containing.Insert(0, outer.Name);

            var outerIsPartial = outer.DeclaringSyntaxReferences
                .Select(reference => reference.GetSyntax(token))
                .OfType<TypeDeclarationSyntax>()
                .Any(d => d.Modifiers.Any(SyntaxKind.PartialKeyword));

            if (!outerIsPartial)
                diagnostics.Add(Diag("KVAL007", "Containing type must be partial",
                    $"'{symbol.Name}' is nested in '{outer.Name}', which must also be declared partial.",
                    true, anchor.Identifier));
        }

        var hasRules = declarations
            .SelectMany(d => d.Members.OfType<MethodDeclarationSyntax>())
            .Any(m => m.Identifier.ValueText == "ConfigureRules");

        if (!hasRules)
            diagnostics.Add(Diag("KVAL002", "No rules configured",
                $"'{symbol.Name}' declares no ConfigureRules method; Validate() will always succeed.",
                false, anchor.Identifier));

        return new ValidatedTypeModel(
            symbol.ContainingNamespace.IsGlobalNamespace ? "" : symbol.ContainingNamespace.ToDisplayString(),
            symbol.Name,
            containing.ToImmutable(),
            diagnostics.ToImmutable());

        static DiagnosticModel Diag(string id, string title, string message, bool isError, SyntaxToken token) {
            var location = token.GetLocation();
            var span     = location.SourceSpan;

            return new DiagnosticModel(
                id, title, message, isError,
                token.SyntaxTree?.FilePath ?? "",
                span.Start, span.Length,
                location.GetLineSpan().Span);
        }
    }
}
