// ReSharper disable UnusedAutoPropertyAccessor.Global

using Kurrent.Surge.Schema.Naming;

namespace Kurrent.Surge.Schema.Catalogs;

/// <summary>
/// Family root for explicit message type registration. Abstract on purpose: a bare
/// <c>[MessageType]</c> is a compile error — every registration must declare its naming source,
/// either a pinned schema name (<see cref="MessageTypeAttribute{T}"/>) or a naming strategy
/// (<see cref="MessageTypeAttribute{T,TStrategy}"/>). The message discovery source generator
/// matches the whole family through this base.
/// </summary>
public abstract class MessageTypeAttribute : Attribute {
    /// <summary>
    /// The registered message type. Always set by the derived attribute's constructor.
    /// </summary>
    public Type MessageType { get; protected init; } = null!;

    /// <summary>
    /// Pinned wire-level schema name, or null when the name comes from a strategy
    /// or the default convention.
    /// </summary>
    public string? SchemaName { get; protected init; }

    /// <summary>
    /// The naming strategy type that derives this type's schema name, or null when the
    /// name is pinned or falls back to the default convention.
    /// </summary>
    public Type? StrategyType { get; protected init; }

    /// <summary>
    /// Key of the catalog this registration joins; omitted → the "Default" catalog.
    /// </summary>
    public string? Catalog { get; set; }
}

/// <summary>
/// Registers <typeparamref name="T"/> as a message. The schema name is pinned when given,
/// otherwise generated by the default <see cref="MessageSchemaNameStrategy"/>.
/// Works on the type itself or at assembly level — the latter also registers types you don't
/// own (e.g. from a referenced contracts package).
/// </summary>
/// <example>
/// <code>
/// [MessageType&lt;OrderPlaced&gt;("order.placed.v1")]              // pinned wire name
/// public record OrderPlaced(string OrderId);
///
/// [assembly: MessageType&lt;ThirdParty.InvoiceIssued&gt;("invoice.issued.v1")]
/// [assembly: MessageType&lt;RaceCar&gt;(Catalog = "Testkit")]       // default-convention name
/// </code>
/// </example>
[AttributeUsage(AttributeTargets.Assembly | AttributeTargets.Class | AttributeTargets.Struct, AllowMultiple = true)]
public class MessageTypeAttribute<T> : MessageTypeAttribute {
    public MessageTypeAttribute(string? schemaName = null) {
        MessageType = typeof(T);
        SchemaName  = schemaName;
    }
}

/// <summary>
/// Registers <typeparamref name="T"/> as a message whose schema name is derived from
/// <typeparamref name="TStrategy"/>. The strategy choice is compile-checked: it must implement
/// <see cref="ISchemaNameStrategy"/> and have a parameterless constructor.
/// </summary>
/// <remarks>
/// Inherits the family root directly (not the pin form) so it never carries a fake schema name:
/// pin and strategy are mutually exclusive naming sources by construction.
/// </remarks>
/// <example>
/// <code>
/// [MessageType&lt;OrderShipped, AcmeNames&gt;]
/// public record OrderShipped(string OrderId);
/// </code>
/// </example>
[AttributeUsage(AttributeTargets.Assembly | AttributeTargets.Class | AttributeTargets.Struct, AllowMultiple = true)]
public sealed class MessageTypeAttribute<T, TStrategy> : MessageTypeAttribute
    where TStrategy : ISchemaNameStrategy, new() {
    public MessageTypeAttribute() {
        MessageType  = typeof(T);
        StrategyType = typeof(TStrategy);
    }
}
