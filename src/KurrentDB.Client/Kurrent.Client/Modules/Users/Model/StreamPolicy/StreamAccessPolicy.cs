namespace Kurrent.Client.Users;

/// <summary>
/// Defines read, write, delete permissions and metadata access for streams.
/// </summary>
/// <remarks>
/// <para>
/// Access policies specify which users and groups can perform specific operations on streams.
/// Users and groups are identified by names or special system roles like $admins, $ops, or $all.
/// </para>
/// </remarks>
[PublicAPI]
public record StreamAccessPolicy {
    /// <summary>
    /// Users and groups with read permission.
    /// </summary>
    /// <remarks>
    /// <para><b>Default:</b> Empty array (no access)</para>
    /// <para>Special roles: $all (everyone), $admins (administrators only), $ops (operators only)</para>
    /// </remarks>
    public string[] Readers { get; init; } = [];

    /// <summary>
    /// Users and groups with write permission.
    /// </summary>
    /// <remarks>
    /// <para><b>Default:</b> Empty array (no access)</para>
    /// <para>Special roles: $all (everyone), $admins (administrators only), $ops (operators only)</para>
    /// </remarks>
    public string[] Writers { get; init; } = [];

    /// <summary>
    /// Users and groups with delete permission.
    /// </summary>
    /// <remarks>
    /// <para><b>Default:</b> Empty array (no access)</para>
    /// <para>Special roles: $all (everyone), $admins (administrators only), $ops (operators only)</para>
    /// </remarks>
    public string[] Deleters { get; init; } = [];

    /// <summary>
    /// Users and groups with metadata read permission.
    /// </summary>
    /// <remarks>
    /// <para><b>Default:</b> Empty array (no access)</para>
    /// <para>Special roles: $all (everyone), $admins (administrators only), $ops (operators only)</para>
    /// </remarks>
    public string[] MetadataReaders { get; init; } = [];

    /// <summary>
    /// Users and groups with metadata write permission.
    /// </summary>
    /// <remarks>
    /// <para><b>Default:</b> Empty array (no access)</para>
    /// <para>Special roles: $all (everyone), $admins (administrators only), $ops (operators only)</para>
    /// </remarks>
    public string[] MetadataWriters { get; init; } = [];

    /// <summary>
    /// Public access policy granting full permissions to all users.
    /// </summary>
    /// <remarks>
    /// Suitable for public streams where all authenticated users should have full access.
    /// </remarks>
    public static readonly StreamAccessPolicy PublicAccess = new() {
        Readers         = ["$all"],
        Writers         = ["$all"],
        Deleters        = ["$all"],
        MetadataReaders = ["$all"],
        MetadataWriters = ["$all"]
    };

    /// <summary>
    /// Admin-only access policy restricting all permissions to administrators.
    /// </summary>
    /// <remarks>
    /// Suitable for system streams or sensitive data requiring administrative access.
    /// </remarks>
    public static readonly StreamAccessPolicy AdminsOnly = new() {
        Readers         = ["$admins"],
        Writers         = ["$admins"],
        Deleters        = ["$admins"],
        MetadataReaders = ["$admins"],
        MetadataWriters = ["$admins"]
    };

    /// <summary>
    /// Default policy for projection streams (public read, admin write/delete).
    /// </summary>
    /// <remarks>
    /// Suitable for streams generated by projections where users need read access
    /// but only administrators should modify the streams.
    /// </remarks>
    public static readonly StreamAccessPolicy ProjectionsDefault = new() {
        Readers         = ["$all"],
        Writers         = ["$admins"],
        Deleters        = ["$admins"],
        MetadataReaders = ["$all"],
        MetadataWriters = ["$admins"]
    };

    /// <summary>
    /// Creates an access policy granting full permissions to the specified users or groups.
    /// </summary>
    /// <param name="usersOrGroups">User names or group names to grant full access.</param>
    public static StreamAccessPolicy FullAccess(params string[] usersOrGroups) => new() {
        Readers         = usersOrGroups,
        Writers         = usersOrGroups,
        Deleters        = usersOrGroups,
        MetadataReaders = usersOrGroups,
        MetadataWriters = usersOrGroups
    };

    /// <summary>
    /// Creates a copy of this policy with the specified readers.
    /// </summary>
    public StreamAccessPolicy WithReaders(params string[] users) => this with { Readers = users };

    /// <summary>
    /// Creates a copy of this policy with the specified writers.
    /// </summary>
    public StreamAccessPolicy WithWriters(params string[] users) => this with { Writers = users };

    /// <summary>
    /// Creates a copy of this policy with the specified deleters.
    /// </summary>
    public StreamAccessPolicy WithDeleters(params string[] users) => this with { Deleters = users };

    /// <summary>
    /// Creates a copy of this policy with the specified metadata readers.
    /// </summary>
    public StreamAccessPolicy WithMetadataReaders(params string[] users) => this with { MetadataReaders = users };

    /// <summary>
    /// Creates a copy of this policy with the specified metadata writers.
    /// </summary>
    public StreamAccessPolicy WithMetadataWriters(params string[] users) => this with { MetadataWriters = users };
}
