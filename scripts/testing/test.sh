#!/usr/bin/env bash
set -uo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$REPO_ROOT"
RUN_ID="$(date +%Y%m%d-%H%M%S)-$(head -c 2 /dev/urandom | xxd -p)"

# --- template -----------------------------------------------------------------
# The canonical way to run tests in this solution. Only two values change:
#   {results_dir}  — unique per run
#   {filter}       — treenode filter with category always enforced
#
# Everything after the template is extra args passed through verbatim.
# Full output goes to {results_dir}/output.log; terminal gets failures + summary.

run() {
  local results_dir="$1" filter="$2"
  shift 2

  mkdir -p "$results_dir"
  local logfile="$results_dir/output.log"

  dotnet test -c Release \
    --no-progress \
    --ignore-exit-code 8 \
    --results-directory "$results_dir" \
    -- \
    --disable-logo \
    --treenode-filter "$filter" \
    --report-trx \
    --log-level Trace \
    --detailed-stacktrace \
    "$@" \
    2>&1 | tee "$logfile" | awk '
      /^failed /        { fail=1 }
      fail && /^[^ ]/   { if (!/^failed /) fail=0 }
      fail              { print; next }
      /^skipped /       { print; next }
      /^Test run summary:/ { summary=1 }
      summary           { print }
    '
}

# --- help ---------------------------------------------------------------------

show_help() {
  cat <<'EOF'
test.sh — canonical test runner for this solution

USAGE
  test.sh <action> <category> [tunit-args...]
  test.sh help

ACTIONS
  run     Execute tests and produce results
  list    Discover and list matching tests without running them

CATEGORIES
  unit          Exclude tests with [Category("Integration")]
  integration   Include only [Category("Integration")] tests
  all           Run both unit and integration tests (no category filter)

  By convention, all integration tests MUST be decorated with [Category("Integration")].
  Tests without this attribute are treated as unit tests. If an integration test appears
  in unit runs or is missing from integration runs, it is missing the category attribute.

EXAMPLES
  test.sh run unit                                       # all unit tests
  test.sh run integration                                # all integration tests
  test.sh run unit --treenode-filter "/*/*/MyTests/*"    # specific class
  test.sh run integration --timeout 30s --fail-fast      # extra TUnit args
  test.sh list unit                                      # list all unit tests
  test.sh list unit --treenode-filter "/*/*/MyTests/*"   # list matching tests

FILTER MERGING
  The category filter is always enforced. If you pass --treenode-filter, the
  category property is appended to the last segment of your filter:

    input:  /*/*/MyTests/*                 → /*/*/MyTests/*[Category!=Integration]
    input:  /*/*/*/*[Priority=High]        → /*/*/*/*[(Priority=High)&(Category!=Integration)]

  TUnit filter docs: https://tunit.dev/docs/execution/test-filters/

RESULTS
  Each run creates a unique folder under .artifacts/test-results/<run-id>/:

    *.trx            TRX files — one per test assembly (auto-named by MTP)
    test-report.md        Markdown report — generated by trx2md.py from *.trx
    output.log       Raw dotnet test output — only for debugging the command itself

  The TRX files are one per test assembly. The markdown report merges all assemblies.
  Always use test-report.md to check test outcomes. Do NOT parse output.log for results.

EXIT CODES
  0   All tests passed
  2   One or more tests failed
  8   Zero tests matched the filter (ignored by --ignore-exit-code 8)
EOF
  exit 0
}

# --- parse action + category --------------------------------------------------

ACTION="${1:-help}"
shift 2>/dev/null || true

case "$ACTION" in
  help|--help|-h) show_help ;;
  run|list) ;;
  *)
    echo "Unknown action: $ACTION" >&2
    echo "Usage: test.sh <run|list> <unit|integration|all> [tunit-args...]" >&2
    exit 1
    ;;
esac

CATEGORY="${1:-}"
shift 2>/dev/null || true

case "$CATEGORY" in
  unit)        CATEGORY_PROP="Category!=Integration" ;;
  integration) CATEGORY_PROP="Category=Integration" ;;
  all)         CATEGORY_PROP="" ;;
  *)
    echo "Unknown category: ${CATEGORY:-<missing>}" >&2
    echo "Usage: test.sh $ACTION <unit|integration|all> [tunit-args...]" >&2
    exit 1
    ;;
esac

# --- build filter -------------------------------------------------------------

# Extract --treenode-filter from user args so we can merge the category into it.
# TUnit only accepts one --treenode-filter value.
PASSTHROUGH=()
USER_FILTER=""
while [[ $# -gt 0 ]]; do
  if [[ "$1" == "--treenode-filter" ]]; then
    USER_FILTER="$2"; shift 2
  else
    PASSTHROUGH+=("$1"); shift
  fi
done

# Append category property to the filter's last segment.
# If the filter already has properties [X=Y], merge with AND: [(X=Y)&(Category...)].
# When CATEGORY_PROP is empty (all), skip the category constraint entirely.
if [[ -z "$CATEGORY_PROP" ]]; then
  FILTER="${USER_FILTER:-/*/*/*/*}"
elif [[ -n "$USER_FILTER" ]]; then
  if [[ "$USER_FILTER" == *"]" ]]; then
    path="${USER_FILTER%%\[*}"
    props="${USER_FILTER#*\[}" && props="${props%]}"
    FILTER="${path}[(${props})&(${CATEGORY_PROP})]"
  else
    FILTER="${USER_FILTER}[${CATEGORY_PROP}]"
  fi
else
  FILTER="/*/*/*/*[${CATEGORY_PROP}]"
fi

# --- list (discovery only) ----------------------------------------------------

if [[ "$ACTION" == "list" ]]; then
  echo "━━ list $CATEGORY tests ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
  echo "  Filter:    $FILTER"
  echo ""
  dotnet test \
    --list-tests \
    --no-progress \
    --ignore-exit-code 8 \
    -- \
    --disable-logo \
    --treenode-filter "$FILTER" \
    2>&1 | grep -v '^Discovering\|^$'
  exit $?
fi

# --- run ----------------------------------------------------------------------

RESULTS_DIR="$REPO_ROOT/.artifacts/test-results/$RUN_ID"

LABEL="$CATEGORY tests"
LINE_RUN="  Run ID:    $RUN_ID"
LINE_FILTER="  Filter:    $FILTER"
LINE_RESULTS="  Results:   .artifacts/test-results/$RUN_ID"
WIDTH=${#LINE_RUN}
(( ${#LINE_FILTER} > WIDTH )) && WIDTH=${#LINE_FILTER}
(( ${#LINE_RESULTS} > WIDTH )) && WIDTH=${#LINE_RESULTS}
(( WIDTH += 2 ))
(( WIDTH < 80 )) && WIDTH=80
RULE=$(printf '━%.0s' $(seq 1 "$WIDTH"))
echo "━━ $LABEL ${RULE:$(( ${#LABEL} + 4 ))}"
echo "$LINE_RUN"
echo "$LINE_FILTER"
echo "$LINE_RESULTS"
echo "$RULE"
echo ""

run "$RESULTS_DIR" "$FILTER" "${PASSTHROUGH[@]}"
EXIT_CODE=$?

# --- cleanup MTP artifact subdirs (duplicate HTML reports in nested dirs) -----

find "$RESULTS_DIR" -mindepth 1 -maxdepth 1 -type d -exec rm -rf {} +

# --- lowercase HTML report filenames to match TRX/MD convention ---------------

for html in "$RESULTS_DIR"/*-report.html; do
  [[ -f "$html" ]] || continue
  lower="$(dirname "$html")/$(basename "$html" | tr '[:upper:]' '[:lower:]')"
  [[ "$html" != "$lower" ]] && mv "$html" "$lower"
done

# --- rename TRX files from timestamps to assembly names -----------------------
# MTP names TRX files like _Mac_2026-05-26_21_15_41.trx — rename to assembly name
# by parsing UnitTest.storage from each file. Filenames stay lowercase.

python3 -c "
import sys, xml.etree.ElementTree as ET
from pathlib import Path

ns = {'t': 'http://microsoft.com/schemas/VisualStudio/TeamTest/2010'}

# Detect OS the same way TUnit does (OperatingSystem.Is* maps to sys.platform)
p = sys.platform
os_name = 'macos' if p == 'darwin' else 'linux' if p == 'linux' else 'windows' if p == 'win32' else 'unknown'

for trx in sorted(Path('$RESULTS_DIR').glob('*.trx')):
    try:
        tree = ET.parse(trx)
        td = tree.find('.//t:UnitTest', ns)
        if td is None:
            trx.unlink()
            continue
        storage = td.get('storage', '')
        if not storage:
            continue
        sp = Path(storage)
        assembly = sp.stem
        framework = sp.parent.name
        new_name = trx.parent / f'{assembly}-{os_name}-{framework}-report.trx'
        if new_name != trx and not new_name.exists():
            trx.rename(new_name)
    except Exception:
        pass
"

# --- TRX report (write .md per assembly + print merged summary) ---------------

SUBTITLE="$CATEGORY tests"
TRX_FILES=("$RESULTS_DIR"/*.trx)
if [[ ${#TRX_FILES[@]} -gt 0 && -f "${TRX_FILES[0]}" ]]; then
  # Generate one .md per .trx (default preset)
  "$REPO_ROOT/scripts/testing/trx2md.py" --subtitle "$SUBTITLE" "${TRX_FILES[@]}"
  # Print merged summary to terminal (compact ai preset)
  echo ""
  "$REPO_ROOT/scripts/testing/trx2md.py" --stdout --preset ai --subtitle "$SUBTITLE" "${TRX_FILES[@]}"
fi

# --- command reproduction block -----------------------------------------------

REL_RESULTS=".artifacts/test-results/$RUN_ID"

EXTRA=""
if [[ ${#PASSTHROUGH[@]} -gt 0 ]]; then
  EXTRA=" \\
    ${PASSTHROUGH[*]}"
fi

CMD_LINES=(
  "  dotnet test \\"
  "    -c Release --no-progress --ignore-exit-code 8 \\"
  "    --results-directory $REL_RESULTS \\"
  "    -- \\"
  "    --disable-logo --log-level Trace --detailed-stacktrace \\"
  "    --treenode-filter \"$FILTER\" \\"
  "    --report-trx${EXTRA}"
)
CMD_WIDTH=0
for line in "${CMD_LINES[@]}"; do
  (( ${#line} > CMD_WIDTH )) && CMD_WIDTH=${#line}
done
(( CMD_WIDTH += 2 ))
CMD_LABEL="command"
CMD_RULE=$(printf '━%.0s' $(seq 1 "$CMD_WIDTH"))

echo ""
echo "━━ $CMD_LABEL ${CMD_RULE:$(( ${#CMD_LABEL} + 4 ))}"
for line in "${CMD_LINES[@]}"; do echo "$line"; done
echo "$CMD_RULE"

exit $EXIT_CODE
